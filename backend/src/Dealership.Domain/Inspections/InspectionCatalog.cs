    public static InspectionPoint GetPoint(string pointCode)
    {
        if (string.IsNullOrWhiteSpace(pointCode))
        {
            throw new ArgumentException("Inspection point code is required.", nameof(pointCode));
        }

        return Points.SingleOrDefault(point => point.Code == pointCode)
            ?? throw new ArgumentException("Inspection point is absent from the retained catalog version.", nameof(pointCode));
    }
